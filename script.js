let currentLang = localStorage.getItem("portfolioLang") || "nl";
const toggleBtn = document.getElementById("lang-toggle");

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("portfolioLang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  if (toggleBtn) {
    toggleBtn.textContent = translations[lang].toggle_label;
  }
}

if (toggleBtn) {
  toggleBtn.addEventListener("click", () => {
    const nextLang = currentLang === "nl" ? "en" : "nl";
    applyLanguage(nextLang);
  });
}

applyLanguage(currentLang);

// Pagina-navigatie tussen Home en subpagina's
const views = document.querySelectorAll(".page-view");
const navLinks = document.querySelectorAll(".nav-link");
const navTriggers = document.querySelectorAll(".nav-link, .nav-trigger");

function showPage(targetId) {
  const targetView = document.getElementById(targetId);
  if (!targetView) return;

  views.forEach((view) => view.classList.remove("active-view"));
  targetView.classList.add("active-view");

  navLinks.forEach((link) => {
    link.classList.toggle("active", link.getAttribute("data-target") === targetId);
  });

  window.scrollTo({ top: 0, behavior: "smooth" });
}

navTriggers.forEach((trigger) => {
  trigger.addEventListener("click", (e) => {
    e.preventDefault();
    const targetId = trigger.getAttribute("data-target");
    if (targetId) {
      showPage(targetId);
      history.replaceState(null, "", `#${targetId}`);
    }
  });
});

// Open direct de juiste subpagina als er een hash in de URL staat (bijv. #projecten)
const initialHash = window.location.hash.replace("#", "");
if (initialHash && document.getElementById(initialHash)) {
  showPage(initialHash);
}